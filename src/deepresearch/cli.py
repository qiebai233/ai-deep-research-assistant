def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog=PROG,
        description=(
            "AI 深度调研助手：输入一个研究问题，自动检索、阅读、交叉验证并生成带引用的报告。"
        ),
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=(
            "examples:\n"
            '  deepresearch run "固态电池2025年产业化进展" --depth deep\n'
            '  deepresearch run "大模型推理成本趋势" --provider mock --search mock   # 离线演示\n'
            "  deepresearch serve --port 8000\n"
            "  deepresearch providers\n"
        ),
    )
    parser.add_argument(
        "--version",
        action="version",
        version=f"{PROG} {__version__}",
        help="显示版本号并退出",
    )
    parser.add_argument(
        "--env-file",
        default=".env",
        metavar="PATH",
        help="从指定 .env 文件读取配置（默认：.env）",
    )
    subparsers = parser.add_subparsers(dest="command", metavar="COMMAND")

    _add_run_parser(subparsers)
    _add_serve_parser(subparsers)
    _add_providers_parser(subparsers)
    _add_init_parser(subparsers)
    _add_version_parser(subparsers)
    return parser


