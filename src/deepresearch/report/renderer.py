"""Markdown report renderer.

The structure is part of the public product contract (``CONTRACTS.md`` 6.2):

    # title
    > **研究问题**：...
    > *生成时间 / 模型 / 深度 / 来源数*

    ## 摘要
    ## 关键发现
    ## 目录
    ## {section headings}
    ## 研究方法与局限
    ## 参考文献
    ---
    *由 DeepResearch v... 生成 · ...*

Only sources that are actually cited survive in the reference list, in order of
first appearance.  Uncited sections, empty sections and reports without any
reference all render gracefully.
"""

from __future__ import annotations

import re
from typing import Dict, List

from .. import __version__
from ..models import Report, ReportSection, Source

__all__ = ["citation_order", "disclaimer_for", "render_markdown"]

_CITE_RE = re.compile(r"\[(S\d+)\]")

