def _language(language: str) -> str:
    return "en" if str(language or "zh").lower().startswith("en") else "zh"


def disclaimer_for(language: str = "zh") -> str:
    """Localised one-line disclaimer used at the bottom of every report."""
    lang = _language(language)
    return str(_LABELS[lang]["disclaimer"]).format(version=__version__)


def citation_order(report: Report) -> List[str]:
    """Source ids in order of first appearance in the report body."""
    ids: List[str] = []
    for section in report.sections:
        for source_id in _CITE_RE.findall(section.body or ""):
            if source_id not in ids:
                ids.append(source_id)
    for section in report.sections:
        for source_id in section.source_ids or []:
            if source_id not in ids:
                ids.append(source_id)
    return ids


def _anchor(text: str, used: Dict[str, int]) -> str:
    """GitHub-style heading anchor with collision suffixes."""
    slug = str(text or "").strip().lower()
    slug = re.sub(r"[^\w\s-]", "", slug, flags=re.UNICODE)
    slug = re.sub(r"[\s_]+", "-", slug).strip("-")
    slug = slug or "section"
    count = used.get(slug, 0)
    used[slug] = count + 1
    return slug if count == 0 else f"{slug}-{count}"


def _format_time(value: str) -> str:
    text = str(value or "").strip().replace("T", " ")
    if text.endswith("Z"):
        text = text[:-1] + " UTC"
    return text


def _kv(label: str, value: str, zh: bool) -> str:
    return f"{label}：{value}" if zh else f"{label}: {value}"


def _meta_line(report: Report, labels: Dict[str, object], reference_count: int, zh: bool) -> str:
    bits: List[str] = []
    generated = _format_time(report.generated_at)
    if generated:
        bits.append(_kv(str(labels["generated"]), generated, zh))
    model = str(getattr(report, "model", "") or "").strip() or str(labels["unknown"])
    bits.append(_kv(str(labels["model"]), model, zh))
    depth = str(getattr(report, "depth", "") or "").strip()
    if depth:
        depth_values = labels["depth_values"]
        depth_label = depth_values.get(depth, depth) if isinstance(depth_values, dict) else depth
    else:
        depth_label = str(labels["unknown"])
    bits.append(_kv(str(labels["depth"]), str(depth_label), zh))
    unit = str(labels["sources_unit"]).format(n=reference_count)
    bits.append(_kv(str(labels["sources"]), unit, zh))
    return " · ".join(bits)


def _reference_lines(report: Report, labels: Dict[str, object], cited: List[str]) -> List[str]:
    lines = [str(labels["references"]), ""]
    available: Dict[str, Source] = {}
    for source in report.references or []:
        available.setdefault(source.id, source)
    ordered = [available[source_id] for source_id in cited if source_id in available]
    if not ordered:
        lines.append(str(labels["empty_references"]))
        return lines
    for index, source in enumerate(ordered, 1):
        title = str(source.title or "").strip() or source.url or source.id
        url = str(source.url or "").strip()
        if url and url not in title:
            lines.append(f"{index}. [{source.id}] {title} — {url}")
        else:
            lines.append(f"{index}. [{source.id}] {title}")
    return lines


def _render_sections(sections: List[ReportSection], empty_placeholder: str) -> List[str]:
    lines: List[str] = []
    for section in sections:
        level = max(2, min(6, int(section.level or 2)))
        heading = str(section.heading or "").strip() or "(untitled)"
        body = str(section.body or "").strip() or empty_placeholder
        lines.extend(["", f"{'#' * level} {heading}", "", body])
    return lines


def render_markdown(report: Report) -> str:
    """Render the complete Markdown report (never mutates ``report``)."""
    lang = _language(report.language)
    labels = _LABELS[lang]
    zh = lang == "zh"

    cited = citation_order(report)
    available_ids = {source.id for source in (report.references or [])}
    reference_count = len([source_id for source_id in cited if source_id in available_ids])

    lines: List[str] = [f"# {report.title or report.question}", ""]
    lines.append(f"> {labels['question']}{'：' if zh else ': '}{report.question}")
    lines.append(f"> *{_meta_line(report, labels, reference_count, zh)}*")

    lines.extend(["", str(labels["summary"]), ""])
    summary = str(report.summary or "").strip()
    lines.append(summary or str(labels["empty_summary"]))

    lines.extend(["", str(labels["key_findings"]), ""])
    takeaways = [str(item).strip() for item in report.key_takeaways if str(item).strip()]
    if takeaways:
        lines.extend(f"- {item}" for item in takeaways)
    else:
        lines.append(str(labels["empty_findings"]))

    sections = list(report.sections or [])
    used: Dict[str, int] = {}
    anchors = [_anchor(section.heading, used) for section in sections]
    lines.extend(["", str(labels["contents"]), ""])
    if sections:
        for index, section in enumerate(sections, 1):
            heading = str(section.heading or "").strip() or f"Section {index}"
            lines.append(f"{index}. [{heading}](#{anchors[index - 1]})")
    else:
        lines.append(str(labels["empty_contents"]))

    lines.extend(_render_sections(sections, str(labels["empty_section"])))

    usage = report.usage
    lines.extend(["", str(labels["methods"]), ""])
    lines.append(
        str(labels["methodology"]).format(
            search_calls=int(getattr(usage, "search_calls", 0) or 0),
            fetches=int(getattr(usage, "fetches", 0) or 0),
            fetch_failures=int(getattr(usage, "fetch_failures", 0) or 0),
            references=reference_count,
        )
    )
    rounds = int(getattr(report, "rounds", 0) or 0)
    if rounds:
        lines.extend(["", str(labels["methodology_rounds"]).format(rounds=rounds)])
    limitations = [str(item).strip() for item in report.limitations if str(item).strip()]
    if not limitations:
        limitations = [str(labels["default_limitation"])]
    lines.append("")
    lines.extend(f"- {item}" for item in limitations)

    lines.append("")
    lines.extend(_reference_lines(report, labels, cited))
    lines.extend(["", "---", ""])
    disclaimer = str(report.disclaimer or "").strip() or disclaimer_for(lang)
    lines.append(f"*{disclaimer}*")
    return "\n".join(lines).rstrip() + "\n"
