"""Command-line interface (``deepresearch``).

Commands::

    deepresearch run "问题" [options]   # run a deep-research session
    deepresearch serve [options]        # start the local web UI
    deepresearch providers              # show providers + current config
    deepresearch init                   # scaffold a .env file
    deepresearch version                # version / environment info
"""

