def _resolve_settings(args: argparse.Namespace, *, demo: bool = False) -> Settings:
    overrides = {
        "depth": getattr(args, "depth", None),
        "language": getattr(args, "lang", None),
        "llm_provider": getattr(args, "provider", None),
        "llm_model": getattr(args, "model", None),
        "llm_base_url": getattr(args, "base_url", None),
        "search_provider": getattr(args, "search", None),
        "out_dir": getattr(args, "out", None),
        "max_sources": getattr(args, "max_sources", None),
        "max_cost_usd": getattr(args, "max_cost", None),
        "max_seconds": getattr(args, "max_seconds", None),
    }
    if demo:
        overrides["llm_provider"] = "mock"
        overrides["search_provider"] = "mock"
    return Settings.from_env(
        env_file=getattr(args, "env_file", ".env"),
        **{k: v for k, v in overrides.items() if v is not None},
    )


def _cmd_run(args: argparse.Namespace) -> int:
    from .api import run_research

    question = " ".join(args.question).strip()
    if not question:
        Console(stream=sys.stderr).error("研究问题不能为空。")
        return 2

    settings = _resolve_settings(args, demo=args.demo)
    progress = Console(quiet=args.quiet or args.stdout)
    summary = Console(quiet=args.stdout)
    progress.banner(__version__)
    if not args.stdout:
        progress.kv(
            [
                ("问题", question),
                ("LLM", f"{settings.llm_provider} / {settings.llm_model}"),
                ("搜索", settings.search_provider),
                (
                    "深度",
                    f"{settings.depth}（最多 {settings.profile().max_sub_questions} 个子问题 / "
                    f"{settings.profile().max_sources} 个来源）",
                ),
                ("语言", settings.language),
            ],
            indent="  ",
        )
        if args.demo or (settings.llm_provider == "mock" and settings.search_provider == "mock"):
            progress.info("离线演示模式：不联网、不需要 API key，报告为确定性示例。")
        progress.line()

    counter = {"n": 0}
    sink = EventSink()

    def _handle(event: ProgressEvent) -> None:
        counter["n"] += 1
        progress.event(counter["n"], event)

    sink.subscribe(_handle)

    started = time.perf_counter()
    result = run_research(
        question,
        settings=settings,
        events=sink,
        save=not args.no_save,
        depth=settings.depth,
        language=settings.language,
    )
    elapsed = time.perf_counter() - started
    report = result.report
    usage = result.usage or report.usage

    if args.stdout:
        sys.stdout.write(report.markdown)
        if not report.markdown.endswith("\n"):
            sys.stdout.write("\n")
        return 0

    summary.line()
    summary.rule("完成")
    summary.line()
    summary.ok(report.title or question)
    summary.kv(
        [
            ("章节", str(len(report.sections))),
            ("来源", f"{len(report.references)} 篇被引用"),
            ("发现", str(len(result.state.findings))),
            (
                "LLM 调用",
                f"{usage.llm_calls} 次 / {usage.prompt_tokens + usage.completion_tokens} tokens",
            ),
            ("成本", f"≈ ${usage.est_cost_usd:.4f}" if usage.est_cost_usd else "免费（mock）"),
            ("耗时", f"{elapsed:.1f}s"),
        ],
    )
    if result.markdown_path:
        summary.line()
        summary.info(f"报告：{result.markdown_path}")
        if result.json_path:
            summary.info(f"数据：{result.json_path}")
        if result.trace_path:
            summary.info(f"轨迹：{result.trace_path}")
    if report.limitations:
        summary.line()
        summary.warn("局限：" + "；".join(report.limitations[:3]))
    return 0


def _cmd_serve(args: argparse.Namespace) -> int:
    try:
        from .server import serve
    except ImportError as exc:  # pragma: no cover - defensive
        Console(stream=sys.stderr).error(f"Web 模块不可用：{exc}")
        return 1

    settings = _resolve_settings(args)
    settings.validate()  # fail fast with actionable errors
    out = Console()
    out.banner(__version__)
    host = args.host
    port = args.port
    display_host = "127.0.0.1" if host in ("0.0.0.0", "::") else host
    out.ok(f"Web UI: http://{display_host}:{port or 8000}")
    out.info(
        f"LLM: {settings.llm_provider} / {settings.llm_model} · 搜索: {settings.search_provider}"
    )
    out.info("按 Ctrl+C 停止服务")
    out.line()
    if args.open:
        webbrowser.open(f"http://{display_host}:{port or 8000}")
    serve(settings, host=host, port=port)
    return 0


def _cmd_providers(_args: argparse.Namespace) -> int:
    settings = _resolve_settings(_args)
    out = Console()
    out.banner(__version__)
    out.heading("当前配置")
    out.kv(settings.describe())
    warnings = settings.validate()
    for warning in warnings:
        out.warn(warning)

    out.heading("LLM 预设（任意 OpenAI 兼容端点）")
    rows: List[List[str]] = []
    for name, preset in PRESETS.items():
        key_env = preset["key_env"]
        if not key_env:
            status = "无需密钥"
        elif os.environ.get(key_env) or (name == settings.llm_provider and settings.llm_api_key):
            status = "已配置"
        else:
            status = f"未配置（{key_env}）"
        rows.append([name, preset["model"] or "-", preset["base_url"] or "-", status])
    out.table(["provider", "默认模型", "端点", "状态"], rows)

    out.heading("搜索后端")
    out.table(
        ["provider", "说明", "状态"],
        [
            [
                "tavily",
                "Tavily Search API（推荐，质量高）",
                "已配置" if settings.tavily_api_key else "未配置（TAVILY_API_KEY）",
            ],
            [
                "searxng",
                "自建 SearXNG 实例",
                "已配置" if settings.searxng_url else "未配置（SEARXNG_URL）",
            ],
            ["none", "不使用搜索引擎（仅模型知识，无外部引用）", "可用"],
            ["mock", "离线合成结果（演示/测试）", "可用"],
        ],
    )
    out.line()
    out.info(f"文档：{DOCS_URL}")
    return 0


def _cmd_init(args: argparse.Namespace) -> int:
    out = Console()
    target = Path(args.output)
    if target.exists() and not args.force:
        out.warn(f"{target} 已存在；如需覆盖请加 --force")
        return 1
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(ENV_TEMPLATE, encoding="utf-8", newline="\n")
    out.ok(f"已生成配置模板：{target.resolve()}")
    out.line()
    out.line("下一步：")
    out.line("  1. 编辑 .env，填入 DEEPRESEARCH_LLM_API_KEY（DeepSeek/OpenAI 等）与 TAVILY_API_KEY")
    out.line('  2. 快速体验：deepresearch run "你的研究问题" --depth standard')
    out.line('  3. 零配置离线演示：deepresearch run "任意问题" --demo')
    out.line("  4. Web 界面：deepresearch serve --open")
    return 0


def _cmd_version(_args: argparse.Namespace) -> int:
    out = Console()
    out.line(f"{PROG} {__version__}")
    out.kv(
        [
            ("Python", platform.python_version()),
            ("平台", platform.platform()),
            ("依赖", "无（仅标准库）"),
            ("源码", str(Path(__file__).resolve().parent)),
        ]
    )
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
