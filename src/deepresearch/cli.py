def main(argv: Optional[Sequence[str]] = None) -> int:
    _ensure_utf8_streams()
    parser = build_parser()
    args = parser.parse_args(list(argv) if argv is not None else None)
    if not args.command:
        parser.print_help()
        return 0
    handlers = {
        "run": _cmd_run,
        "serve": _cmd_serve,
        "providers": _cmd_providers,
        "init": _cmd_init,
        "version": _cmd_version,
    }
    handler = handlers[args.command]
    try:
        return int(handler(args) or 0)
    except KeyboardInterrupt:
        Console(stream=sys.stderr).warn("已取消。")
        return 130
    except ConfigError as exc:
        _print_error(
            args,
            f"配置错误：{exc}",
            hint="运行 `deepresearch init` 生成配置，或使用 `--demo` 离线体验。",
        )
        return 2
    except DeepResearchError as exc:
        _print_error(args, f"{type(exc).__name__}：{exc}")
        return 1
    except Exception as exc:  # noqa: BLE001 - last-resort CLI guard
        if getattr(args, "debug", False):
            raise
        _print_error(
            args, f"未预期的错误：{type(exc).__name__}: {exc}", hint="加上 --debug 查看完整堆栈。"
        )
        return 1


def _ensure_utf8_streams() -> None:
    """Force UTF-8 on redirected stdout/stderr (Windows defaults to a legacy code page)."""
    for stream in (sys.stdout, sys.stderr):
        reconfigure = getattr(stream, "reconfigure", None)
        if reconfigure is None:
            continue
        try:
            reconfigure(encoding="utf-8", errors="replace")
        except (ValueError, OSError):  # pragma: no cover - exotic streams
            pass


def _print_error(args: argparse.Namespace, message: str, hint: str = "") -> None:
    err = Console(stream=sys.stderr)
    err.error(message)
    if hint:
        err.info(hint)


